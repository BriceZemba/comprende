"""Sanity checks on the coverage catalog, written to data/validation_es.md.

1. Distribution of the vocabulary needed for 95% / 98% coverage, to compare with
   Webb & Rodgers (2009): about 3,000 word families + proper nouns and marginal
   words for 95% of English film dialogue. Lemmas are narrower than families, so
   we expected numbers at or above that.
2. Genre check. Hypothesis: animation and family titles, written partly for children,
   need fewer words than dramas. The script prints whether the data support it.
"""
import json
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from comprende_pipeline.config import CACHE_DIR, DATA_DIR  # noqa: E402
from comprende_pipeline.coverage import coverage_at  # noqa: E402


def pct(xs, p):
    xs = sorted(xs)
    return xs[min(len(xs) - 1, int(p / 100 * len(xs)))]


def main():
    cat = json.loads((DATA_DIR / "catalog_es.json").read_text(encoding="utf-8"))["titles"]
    genres = {}
    for c in cat:
        f = CACHE_DIR / "lemmas" / f"{c['imdb']}.json"
        genres[c["imdb"]] = json.loads(f.read_text(encoding="utf-8"))["meta"].get("genre", "")

    summary = {"titles": len(cat)}
    lines = ["# Catalog validation (generated by pipeline/scripts/validate_catalog.py)", ""]
    lines.append(f"Titles measured: {len(cat)}")
    lines.append("")
    for target, key in ((0.95, "vocab_for_95"), (0.98, "vocab_for_98")):
        vals = [c[key] for c in cat if c[key] is not None]
        never = sum(1 for c in cat if c[key] is None)
        summary[f"median_{key}"] = statistics.median(vals)
        summary[f"p25_{key}"], summary[f"p75_{key}"] = pct(vals, 25), pct(vals, 75)
        lines.append(
            f"- Lemmas needed for {target:.0%} coverage: median {statistics.median(vals):,.0f}, "
            f"25th pct {pct(vals, 25):,}, 75th pct {pct(vals, 75):,}; not reached within 20,000 lemmas: {never}"
        )
    for v in (1000, 2000, 3000, 5000):
        vals = [coverage_at(c["coverage"], v) for c in cat]
        summary[f"median_coverage_at_{v}"] = round(statistics.median(vals), 4)
        lines.append(f"- Median coverage knowing {v:,} lemmas: {statistics.median(vals):.1%}")
    lines.append("")
    lines.append("## Genre check (hypothesis: animation/family titles need fewer words than dramas)")
    lines.append("")
    lines.append("| Group | Titles | Median coverage at 3,000 lemmas | Median lemmas for 95% |")
    lines.append("|---|---|---|---|")
    groups = {
        "Animation or Family": lambda g: "Animation" in g or "Family" in g,
        "Drama, not Animation/Family/Comedy": lambda g: "Drama" in g
        and not any(x in g for x in ("Animation", "Family", "Comedy")),
        "History or War": lambda g: "History" in g or "War" in g,
        "Comedy": lambda g: "Comedy" in g,
    }
    medians, counts = {}, {}
    for name, test in groups.items():
        sel = [c for c in cat if test(genres[c["imdb"]])]
        if not sel:
            continue
        cov = statistics.median(coverage_at(c["coverage"], 3000) for c in sel)
        medians[name] = cov
        counts[name] = len(sel)
        need = [c["vocab_for_95"] for c in sel if c["vocab_for_95"]]
        need_txt = f"{statistics.median(need):,.0f}" if need else "n/a"
        lines.append(f"| {name} | {len(sel)} | {cov:.1%} | {need_txt} |")
    lines.append("")
    anim, drama = medians.get("Animation or Family"), medians.get("Drama, not Animation/Family/Comedy")
    if anim is not None and drama is not None:
        verdict = "supported" if anim > drama else "not supported"
        summary["genre_check"] = {"hypothesis": "animation/family titles need fewer words than dramas",
                                  "result": verdict, "animation_family": round(anim, 4), "drama": round(drama, 4),
                                  "animation_family_titles": counts["Animation or Family"]}
        lines.append(f"Result: hypothesis {verdict} (animation/family {anim:.1%} vs drama {drama:.1%} at 3,000 lemmas).")
        lines.append("")
    lines.append("Genre labels come from the subtitle file metadata (IMDb genres as recorded by OpenSubtitles).")
    out = "\n".join(lines) + "\n"
    (DATA_DIR / "validation_es.md").write_text(out, encoding="utf-8")
    (DATA_DIR / "validation_es.json").write_text(json.dumps(summary, indent=1), encoding="utf-8")
    print(out)


if __name__ == "__main__":
    main()
