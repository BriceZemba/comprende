"""Compare recommendation runs on the same 20 profiles. Writes eval/results/report.md.

    python eval/metrics.py

Metrics, per system:
  - Spanish-original rate: share of titles verified on Wikidata as originally in Spanish.
  - Not Spanish / unverified: real titles in another language; titles no film/series matched.
  - Personalisation: distinct titles / all titles, and mean Jaccard overlap between profiles
    (0 = every profile gets different titles, 1 = everyone gets the same list).
  - Most repeated titles.
  - Level fit: for titles whose dialogue we measured, the share the learner would follow at
    >= 95% coverage given the profile's vocabulary size, and the share below 90%; over all ten
    picks, and over the first five picks shown (Comprende's later picks include labelled
    "stretch" titles on purpose, so the first five are the like-for-like comparison).
"""
import itertools
import json
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "pipeline"))
from comprende_pipeline.coverage import coverage_at  # noqa: E402

SYSTEMS = {"llm_only": "Gemini alone (no Qloo, no subtitles)",
           "no_qloo": "Comprende without Qloo (popularity instead of taste)",
           "comprende": "Comprende (Qloo + subtitle coverage)"}


def key(t: dict) -> str:
    return t.get("imdb") or t.get("wikidata") or t["title"].lower()


def analyse(run: dict, profiles: dict, catalog: dict) -> dict:
    rows = run["results"]
    titles = [t for r in rows for t in r["titles"]]
    n = len(titles)
    cls = Counter(t["class"] for t in titles)
    sets = [{key(t) for t in r["titles"]} for r in rows]
    pairs = list(itertools.combinations(sets, 2))
    jacc = sum(len(a & b) / len(a | b) for a, b in pairs if a | b) / len(pairs) if pairs else 0.0
    names = {}
    for t in titles:
        names.setdefault(key(t), t.get("matched") or t["title"])
    repeated = Counter(key(t) for t in titles).most_common(8)
    fits, first5 = [], []
    for r in rows:
        v = profiles[r["id"]]["vocab_size"]
        for i, t in enumerate(r["titles"]):
            if t.get("imdb") in catalog:
                c = coverage_at(catalog[t["imdb"]], v)
                fits.append(c)
                if i < 5:  # the first five picks the learner sees
                    first5.append(c)
    return {
        "titles": n,
        "spanish_original": (cls["spanish_original"] + cls["measured"]) / n if n else 0,
        "measured": cls["measured"],
        "not_spanish": cls["not_spanish"] / n if n else 0,
        "unverified": cls["unverified"] / n if n else 0,
        "distinct_share": len({key(t) for t in titles}) / n if n else 0,
        "mean_jaccard": jacc,
        "repeated": [(names[k], c) for k, c in repeated],
        "fit_n": len(fits),
        "fit_95": sum(f >= 0.95 for f in fits) / len(fits) if fits else None,
        "fit_below_90": sum(f < 0.90 for f in fits) / len(fits) if fits else None,
        "first5_n": len(first5),
        "first5_95": sum(f >= 0.95 for f in first5) / len(first5) if first5 else None,
        "first5_below_90": sum(f < 0.90 for f in first5) / len(first5) if first5 else None,
        "unverified_titles": sorted({t["title"] for t in titles if t["class"] == "unverified"}),
        "not_spanish_titles": sorted({t["title"] for t in titles if t["class"] == "not_spanish"}),
    }


def pct(x):
    # One decimal, same as the web methods page, so both show identical figures.
    return "n/a" if x is None else f"{x:.1%}"


def main():
    profiles = {p["id"]: p for p in json.loads((HERE / "profiles.json").read_text(encoding="utf-8"))["profiles"]}
    cat = json.loads((ROOT / "data" / "catalog_es.json").read_text(encoding="utf-8"))
    catalog = {t["imdb"]: t["coverage"] for t in cat["titles"]}
    found = {}
    for name in SYSTEMS:
        f = HERE / "results" / f"{name}.json"
        if f.exists():
            found[name] = (json.loads(f.read_text(encoding="utf-8")), analyse(json.loads(f.read_text(encoding="utf-8")),
                                                                              profiles, catalog))
    lines = ["# Evaluation report (generated by eval/metrics.py)", "",
             f"{len(profiles)} fixed taste profiles (`eval/profiles.json`), 10 titles requested per profile.", ""]
    lines += ["| Metric | " + " | ".join(SYSTEMS[s] for s in found) + " |", "|---|" + "---|" * len(found)]
    rows = [
        ("Titles returned", lambda a: str(a["titles"])),
        ("Verified Spanish-original", lambda a: pct(a["spanish_original"])),
        ("Real title, not originally Spanish", lambda a: pct(a["not_spanish"])),
        ("Not verified automatically (not proof of invention)", lambda a: pct(a["unverified"])),
        ("Distinct titles / all titles", lambda a: pct(a["distinct_share"])),
        ("Mean overlap between profiles (Jaccard)", lambda a: f"{a['mean_jaccard']:.2f}"),
        ("Titles with measured dialogue", lambda a: str(a["fit_n"])),
        ("…of which followable (≥ 95% coverage at the profile's level)", lambda a: pct(a["fit_95"])),
        ("…of which too hard (< 90% coverage)", lambda a: pct(a["fit_below_90"])),
        ("First five picks with measured dialogue", lambda a: str(a["first5_n"])),
        ("…of which followable (≥ 95%)", lambda a: pct(a["first5_95"])),
        ("…of which too hard (< 90%)", lambda a: pct(a["first5_below_90"])),
    ]
    for label, fn in rows:
        lines.append(f"| {label} | " + " | ".join(fn(a) for _, a in found.values()) + " |")
    for name, (run, a) in found.items():
        lines += ["", f"## {SYSTEMS[name]}", "", f"Run at {run.get('run_at', '?')}; model(s): "
                  f"{', '.join(sorted({r.get('model', '-') or '-' for r in run['results']}))}.", "",
                  "Most repeated titles: " + "; ".join(f"{n} ({c}/{len(profiles)})" for n, c in a["repeated"]) + ".", ""]
        if a["not_spanish_titles"]:
            lines.append("Not originally Spanish: " + "; ".join(a["not_spanish_titles"]) + ".")
        if a["unverified_titles"]:
            lines.append("")
            lines.append("Not verified automatically (a title being here does not mean it is invented; still to check by hand): " + "; ".join(a["unverified_titles"]) + ".")
    out = "\n".join(lines) + "\n"
    (HERE / "results" / "report.md").write_text(out, encoding="utf-8")
    summary = {name: {k: v for k, v in a.items() if not k.endswith("_titles")} | {"label": SYSTEMS[name],
               "run_at": run.get("run_at")} for name, (run, a) in found.items()}
    (HERE / "results" / "summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=1), encoding="utf-8")
    print(out)


if __name__ == "__main__":
    main()
