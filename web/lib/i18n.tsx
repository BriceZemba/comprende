export const MESSAGES: Record<Lang, Messages> = { en, fr, es };

// ---- provider ----------------------------------------------------------------

interface I18n { lang: Lang; setLang: (l: Lang) => void; t: Messages; f: { int: (x: number) => string; pct1: (x: number | null | undefined) => string; pct0: (x: number) => string; pctFloor: (x: number) => string } }

const Ctx = createContext<I18n | null>(null);

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("lang");
    if (saved && (LANGS as string[]).includes(saved)) return saved as Lang;
  } catch { /* storage blocked: fall back to the browser language */ }
  const nav = typeof navigator !== "undefined" ? navigator.language.slice(0, 2) : "en";
  return (LANGS as string[]).includes(nav) ? (nav as Lang) : "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en"); // server render is English; the saved choice applies after mount
  useEffect(() => { setLangState(initialLang()); }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
    // Next writes the English metadata title back after history changes; keep the translated one.
    const want = MESSAGES[lang].docTitle;
    const apply = () => { if (document.title !== want) document.title = want; };
    apply();
    const watcher = new MutationObserver(apply);
    watcher.observe(document.head, { subtree: true, childList: true, characterData: true });
    return () => watcher.disconnect();
  }, [lang]);
  const setLang = (l: Lang) => {
    setLangState(l);
    try { localStorage.setItem("lang", l); } catch { /* not persisted */ }
  };
  const value: I18n = {
    lang, setLang, t: MESSAGES[lang],
    f: { int: (x) => fmt.int(lang, x), pct1: (x) => fmt.pct1(lang, x), pct0: (x) => fmt.pct0(lang, x), pctFloor: (x) => fmt.pctFloor(lang, x) },
  };
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error("useI18n outside I18nProvider");
  return v;
}
