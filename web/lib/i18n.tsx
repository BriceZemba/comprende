export const fmt = {
  int: (lang: Lang, x: number) => Math.round(x).toLocaleString(LOCALE[lang]),
  // One decimal: the same figures as eval/results/report.md and data/validation_es.md.
  pct1: (lang: Lang, x: number | null | undefined) =>
    x == null ? "–" : new Intl.NumberFormat(LOCALE[lang], { style: "percent", minimumFractionDigits: 1, maximumFractionDigits: 1 }).format(x),
  pct0: (lang: Lang, x: number) =>
    new Intl.NumberFormat(LOCALE[lang], { style: "percent", maximumFractionDigits: 0 }).format(x),
  // Floored whole percent: 94.9% must not display as 95% under the 95% threshold.
  pctFloor: (lang: Lang, x: number) =>
    new Intl.NumberFormat(LOCALE[lang], { style: "percent", maximumFractionDigits: 0 }).format(Math.floor(x * 100) / 100),
};

